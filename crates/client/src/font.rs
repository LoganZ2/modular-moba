/// Glyph index for a character (unknown characters render as '?').
pub fn glyph_index(c: char) -> usize {
    let c = c as u32;
    if (32..=126).contains(&c) {
        (c - 32) as usize
    } else {
        ('?' as u32 - 32) as usize
    }
}

/// RGBA atlas: all glyphs side by side, each in a 6x8 cell.
pub fn atlas_rgba(color: u32) -> (usize, usize, Vec<u8>) {
    let w = GLYPHS.len() * 6;
    let h = 8;
    let mut px = vec![0u8; w * h * 4];
    let (r, g, b) = ((color >> 16) as u8, (color >> 8) as u8, color as u8);
    for (gi, rows) in GLYPHS.iter().enumerate() {
        for (y, row) in rows.iter().enumerate() {
            for x in 0..GLYPH_W {
                if row & (1 << (GLYPH_W - 1 - x)) != 0 {
                    let i = (y * w + gi * 6 + x) * 4;
                    px[i] = r;
                    px[i + 1] = g;
                    px[i + 2] = b;
                    px[i + 3] = 255;
                }
            }
        }
    }
    (w, h, px)
}

pub fn text_width(s: &str) -> f64 {
    let n = s.chars().count() as f64;
    if n == 0.0 {
        0.0
    } else {
        n * ADVANCE - 1.0
    }
}

/// Word-wrap `s` to lines of at most `max_px` pixels.
pub fn wrap(s: &str, max_px: f64) -> Vec<String> {
    let max_chars = ((max_px + 1.0) / ADVANCE).floor().max(1.0) as usize;
    let mut lines = Vec::new();
    let mut cur = String::new();
    for word in s.split_whitespace() {
        let extra = if cur.is_empty() { word.len() } else { cur.len() + 1 + word.len() };
        if extra > max_chars && !cur.is_empty() {
            lines.push(std::mem::take(&mut cur));
        }
        if !cur.is_empty() {
            cur.push(' ');
        }
        cur.push_str(word);
        while cur.len() > max_chars {
            let rest = cur.split_off(max_chars);
            lines.push(std::mem::replace(&mut cur, rest));
        }
    }
    if !cur.is_empty() {
        lines.push(cur);
    }
    lines
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wraps() {
        let l = wrap("the quick brown fox jumps", 60.0);
        assert!(l.iter().all(|x| text_width(x) <= 60.0));
        assert_eq!(l.join(" "), "the quick brown fox jumps");
        assert_eq!(glyph_index('A'), 33);
        assert_eq!(glyph_index('中'), glyph_index('?'));
    }
}
